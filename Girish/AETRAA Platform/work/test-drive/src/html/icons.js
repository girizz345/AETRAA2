// For a page script: every symbol mapped straight to its <svg>.
//   var SYM = ${symbolIcons(16)};   then   SYM['▦'] || '▦'
export function symbolIcons(size = 16) {
  const out = {};
  for (const [sym, name] of Object.entries(SYMBOL_ICON)) out[sym] = icon(name, size);
  return JSON.stringify(out);
}

export function icon(name, size = 16) {
  const d = ICON_PATHS[name] || ICON_PATHS.info;
  return '<svg class="ic" width="' + size + '" height="' + size + '" viewBox="0 0 24 24" fill="none" ' +
    'stroke="currentColor" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round" ' +
    'aria-hidden="true" focusable="false">' + d + '</svg>';
}

// The same set for a page's own script, which builds rows in the browser:
//   var IC = ${iconsFor(['check', 'clock'])};   then   IC.check
export function iconsFor(names, size = 14) {
  const out = {};
  for (const n of names) out[n] = icon(n, size);
  return JSON.stringify(out);
}
